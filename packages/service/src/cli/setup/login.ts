/**
 * Start-at-login units (issue #108, PRD §14).
 *
 * `unvibe setup` writes one of these alongside the `unvibe://` handler so
 * the service is already running when the browser opens the bookmark —
 * nothing in the browser can start it. macOS gets a launchd agent,
 * Linux a systemd user unit. Both run the installed CLI's
 * `start --foreground` with the port and data dir baked in at setup time
 * (re-run setup after changing them), and both set `UNVIBE_IDLE_MS=0`: a
 * login-started service never idle-exits (owner decision on #108). A
 * manually started service keeps the normal idle exit.
 *
 * Only `UNVIBE_PORT`, `UNVIBE_DATA_DIR` and `UNVIBE_IDLE_MS` are baked in —
 * never the whole environment, and never `GITHUB_TOKEN` (PRD §15: `gh`
 * must run with it unset).
 *
 * Pure builders (snapshot-tested, including paths with spaces) + paths
 * under a home dir. Enabling/disabling goes through the injected runner so
 * tests assert the commands without touching the real login session.
 *
 * Identity (label, unit name, file paths) lives in
 * `update/service-manager.ts` — the self-contained update-helper bundle
 * imports it from there, so this module re-exports it rather than
 * duplicating it.
 */

import { LAUNCHD_LABEL } from "../../update/service-manager.js";

export {
  LAUNCHD_LABEL,
  LAUNCHD_PLIST_FILENAME,
  SYSTEMD_UNIT_NAME,
  launchdPlistPath,
  systemdUnitPath,
} from "../../update/service-manager.js";

export interface LoginUnitOpts {
  nodePath: string;
  cliPath: string;
  port: number;
  dataDir: string;
}

/** XML-escape for plist string values. */
function xmlEscape(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/** launchd agent plist: run at load, restart on crash only, never idle-exit. */
export function launchdPlistContent(opts: LoginUnitOpts): string {
  const { nodePath, cliPath, port, dataDir } = opts;
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    '<plist version="1.0">',
    "<dict>",
    "  <key>Label</key>",
    `  <string>${LAUNCHD_LABEL}</string>`,
    "  <key>ProgramArguments</key>",
    "  <array>",
    `    <string>${xmlEscape(nodePath)}</string>`,
    `    <string>${xmlEscape(cliPath)}</string>`,
    "    <string>start</string>",
    "    <string>--foreground</string>",
    "  </array>",
    "  <key>EnvironmentVariables</key>",
    "  <dict>",
    "    <key>UNVIBE_PORT</key>",
    `    <string>${port}</string>`,
    "    <key>UNVIBE_DATA_DIR</key>",
    `    <string>${xmlEscape(dataDir)}</string>`,
    "    <key>UNVIBE_IDLE_MS</key>",
    "    <string>0</string>",
    "  </dict>",
    "  <key>RunAtLoad</key>",
    "  <true/>",
    // Restart on crash only (a deliberate stop — `unvibe stop` — exits 0
    // and is respected; with plain `KeepAlive true` launchd would undo
    // the stop at once). Mirrors systemd `Restart=on-failure`.
    "  <key>KeepAlive</key>",
    "  <dict>",
    "    <key>SuccessfulExit</key>",
    "    <false/>",
    "  </dict>",
    "  <key>StandardOutPath</key>",
    `  <string>${xmlEscape(dataDir)}/unvibe-login.log</string>`,
    "  <key>StandardErrorPath</key>",
    `  <string>${xmlEscape(dataDir)}/unvibe-login.err.log</string>`,
    "</dict>",
    "</plist>",
    "",
  ].join("\n");
}

/** systemd quoting: double quotes with `\`, `"`, `$` and backtick escaped. */
export function systemdQuote(s: string): string {
  if (/^[A-Za-z0-9_@%+=:,./-]+$/.test(s)) return s;
  return `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "$$").replace(/`/g, "'")}"`;
}

/**
 * One systemd `Environment=` line. The whole `NAME=value` assignment is
 * quoted when it needs it (the documented shape), so data dirs with
 * spaces work.
 */
export function systemdEnv(name: string, value: string): string {
  const bare = `${name}=${value}`;
  if (/^[A-Za-z0-9_]+=[A-Za-z0-9_@%+=:,./-]+$/.test(bare)) return `Environment=${bare}`;
  const escaped = bare.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  return `Environment="${escaped}"`;
}

/** systemd user unit: start at login, restart on failure, never idle-exit. */
export function systemdUnitContent(opts: LoginUnitOpts): string {
  const { nodePath, cliPath, port, dataDir } = opts;
  return [
    "# Generated by `unvibe setup`. Re-run setup after changing the port or data dir.",
    "[Unit]",
    "Description=Unvibe local review service",
    "After=network-online.target",
    "",
    "[Service]",
    "Type=simple",
    `ExecStart=${systemdQuote(nodePath)} ${systemdQuote(cliPath)} start --foreground`,
    systemdEnv("UNVIBE_PORT", String(port)),
    systemdEnv("UNVIBE_DATA_DIR", dataDir),
    "Environment=UNVIBE_IDLE_MS=0",
    "Restart=on-failure",
    "RestartSec=5",
    "",
    "[Install]",
    "WantedBy=default.target",
    "",
  ].join("\n");
}
