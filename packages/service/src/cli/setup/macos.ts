/**
 * macOS `unvibe://` helper contents (PRD §14).
 *
 * Pure builders (snapshot-tested, including paths with spaces) + the
 * impure installer that compiles and registers the helper. The actual
 * `osacompile`/`lsregister` calls go through an injected runner so Linux
 * CI can exercise the orchestration with a stub.
 *
 * Why an AppleScript applet compiled with `osacompile`: macOS delivers a
 * custom-URL open as an Apple Event (`open location`). A bundle whose
 * executable is a plain shell script has no Apple-event handling at all,
 * so LaunchServices would launch it but silently drop the URL. An
 * `osacompile`d applet natively implements `on open location`. Because
 * the .app is generated on the user's own machine (never downloaded), it
 * carries no quarantine attribute: Gatekeeper stays out of the way and no
 * Apple signing is needed.
 */

export const HELPER_BUNDLE_ID = "com.unvibe.helper";
export const URL_SCHEME = "unvibe";
export const HELPER_APP_NAME = "Unvibe.app";

export function helperAppPath(homeDir: string): string {
  return `${homeDir}/Applications/${HELPER_APP_NAME}`;
}

/** Quote a string for embedding in an AppleScript `"..."` literal. */
export function applescriptQuote(s: string): string {
  return `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

/** POSIX shell single-quoting (`'` → `'\''`). */
export function shellQuote(s: string): string {
  if (/^[A-Za-z0-9_@%+=:,./-]+$/.test(s)) return s;
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

/**
 * AppleScript source for the helper: `unvibe://start` (and a bare app
 * open) starts the service via the installed CLI. Absolute paths are
 * baked in because Finder-launched apps do not inherit the shell's PATH;
 * the service itself then repairs its PATH from the login shell (PRD §14).
 */
export function appleScriptSource(nodePath: string, cliPath: string): string {
  // Shell-quote first (paths may contain spaces), then wrap the whole
  // command as one AppleScript string literal.
  const cmd = `${shellQuote(nodePath)} ${shellQuote(cliPath)} start > /dev/null 2>&1 &`;
  // do shell script runs /bin/sh; the trailing & returns immediately while
  // `unvibe start` daemonises the service in the background.
  const quoted = applescriptQuote(cmd);
  return [
    `-- Unvibe link handler, generated by \`unvibe setup\`.`,
    `-- Handles ${URL_SCHEME}://start by starting the local service.`,
    ``,
    `on open location this_URL`,
    `  if this_URL starts with "${URL_SCHEME}://start" then`,
    `    do shell script ${quoted}`,
    `  end if`,
    `end open location`,
    ``,
    `on run`,
    `  do shell script ${quoted}`,
    `end run`,
    ``,
  ].join("\n");
}

/**
 * Patch an `osacompile`-generated Info.plist to register the `unvibe://`
 * URL scheme (`CFBundleURLTypes`). Inserts before the top-level dict's
 * closing tag; throws when the plist has no top-level dict.
 */
export function patchInfoPlist(plist: string): string {
  const close = plist.lastIndexOf("</dict>");
  if (close < 0) throw new Error("patchInfoPlist: no </dict> in Info.plist");
  const snippet = [
    "  <key>CFBundleURLTypes</key>",
    "  <array>",
    "    <dict>",
    "      <key>CFBundleURLName</key>",
    `      <string>${HELPER_BUNDLE_ID}.url</string>`,
    "      <key>CFBundleURLSchemes</key>",
    "      <array>",
    `        <string>${URL_SCHEME}</string>`,
    "      </array>",
    "    </dict>",
    "  </array>",
  ].join("\n");
  return `${plist.slice(0, close)}${snippet}\n${plist.slice(close)}`;
}

/** Path to `lsregister` (LaunchServices registration). */
export const LSREGISTER =
  "/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister";
