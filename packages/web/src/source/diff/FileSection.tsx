function hasComment(
  slots: LineSlots,
  commentedLines: ReadonlySet<string>,
  fileKey: string,
  line: number,
): boolean {
  // M4: the line-number icon marks comment threads only. Expansion slots
  // render their own row without the icon; the dotted link on the quoted
  // text is their indicator (PRD §4.7).
  void slots;
  return commentedLines.has(slotKey(fileKey, line));
}

function lineTip(
  slots: LineSlots,
  commentedLines: ReadonlySet<string>,
  fileKey: string,
  line: number,
): string {
  return hasComment(slots, commentedLines, fileKey, line) ? "Show comment" : `Comment on line ${line}`;
}

function SlotRow({ cols, html }: { cols: number; html: ReactNode }): ReactNode {
  return (
    <tr className="pr">
      <td colSpan={cols}>
        <div className="pin" style={{ padding: "6px 10px 6px 34px", background: "var(--bg)" }}>
          {html}
        </div>
      </td>
    </tr>
  );
}

interface RowProps {
  fileKey: string;
  hunk: Hunk;
  slots: LineSlots;
  commentedLines: ReadonlySet<string>;
  highlight: LineRange | null;
  onLineClick: ((fileKey: string, line: number) => void) | undefined;
  toks: { old: (LineTokens | null)[]; new: (LineTokens | null)[] } | null;
}

function inHighlight(highlight: LineRange | null, n: number | undefined): boolean {
  return n !== undefined && highlight !== null && n >= highlight.start && n <= highlight.end;
}

/**
 * Code-cell content as an opaque HTML string (issue #101).
 *
 * The span carries `dangerouslySetInnerHTML` and never React children, so
 * the cell's text nodes are anonymous: anchor marks may wrap, split and
 * merge them freely, and React only ever swaps the whole string (plain →
 * token spans on upgrade, new text on patches). Null segs render today's
 * plain text; plain runs stay spanless so the DOM (and copy-paste) carries
 * no artefacts; only colours change, so there is no layout shift.
 */
function codeCellHtml(prefix: string, text: string, segs: LineTokens | null): string {
  return escapeHtml(prefix) + codeLineHtml(text, segs);
}

/** The `#`-comment fallback only applies to unhighlighted (plain) rows. */
function plainCommentClass(text: string, segs: LineTokens | null): string | undefined {
  return segs === null && /^\s*#/.test(text) ? "cm" : undefined;
}

function UnifiedRows({ fileKey, hunk, slots, commentedLines, highlight, onLineClick, toks }: RowProps): ReactNode {
  const lines = hunk.lines;
  return (
    <>
      {lines.map((r, ri) => {
        const n = r.newLine;
        const hl = inHighlight(highlight, n);
        const commented = n !== undefined && hasComment(slots, commentedLines, fileKey, n);
        // Unified rows show the new-side tokens (the post-image under
        // review); deleted rows show the old side.
        const segs = toks ? (r.kind === "del" ? toks.old[ri] : toks.new[ri]) ?? null : null;
        return (
          <Fragment key={`${r.kind}-${r.oldLine ?? ""}-${n ?? ""}-${ri}`}>
            <tr className={`${r.kind}${hl ? " hl" : ""}`} id={n !== undefined ? `L-${fileKey}-${n}` : undefined}>
              <td className="n">{r.oldLine ?? ""}</td>
              <td
                className={`n${n !== undefined ? " new" : ""}${commented ? " hc" : ""}`}
                data-line={n !== undefined ? `${fileKey}:${n}` : undefined}
                data-tip={n !== undefined ? lineTip(slots, commentedLines, fileKey, n) : undefined}
                onClick={n !== undefined && onLineClick ? () => onLineClick(fileKey, n) : undefined}
              >
                {commented ? <Icon name="comment" /> : null}
                {n ?? ""}
              </td>
              <td className="c">
                <span
                  className={plainCommentClass(r.text, segs)}
                  dangerouslySetInnerHTML={{
                    __html: codeCellHtml(r.kind === "add" ? "+" : r.kind === "del" ? "-" : " ", r.text, segs),
                  }}
                />
              </td>
            </tr>
            {n !== undefined && slots[slotKey(fileKey, n)] != null ? (
              <SlotRow cols={3} html={slots[slotKey(fileKey, n)]} />
            ) : null}
          </Fragment>
        );
      })}
    </>
  );
}

function SplitRows({ fileKey, hunk, slots, commentedLines, highlight, onLineClick, toks }: RowProps): ReactNode {
  const rows: SplitRow[] = pairSplitRows(hunk.lines);
  // Split pairing zips del/add runs; token rows follow the hunk line index,
  // so resolve each cell's segments from its source line index.
  const lineIndex = new Map<HunkLine, number>();
  hunk.lines.forEach((l, i) => {
    if (!lineIndex.has(l)) lineIndex.set(l, i);
  });
  const cell = (line: HunkLine | undefined, side: "o" | "n"): ReactNode => {
    if (!line) {
      return (
        <>
          <td className="n empty" />
          <td className="c empty" />
        </>
      );
    }
    const num = side === "o" ? line.oldLine : line.newLine;
    const cls = line.kind === "ctx" ? "" : line.kind;
    const clickable = side === "n" && num !== undefined;
    const commented = clickable && hasComment(slots, commentedLines, fileKey, num);
    const li = lineIndex.get(line);
    const segs = toks && li !== undefined ? (side === "o" ? toks.old[li] : toks.new[li]) ?? null : null;
    return (
      <>
        <td
          className={`n${clickable ? " new" : ""}${commented ? " hc" : ""} ${cls}`}
          data-line={clickable ? `${fileKey}:${num}` : undefined}
          data-tip={clickable ? lineTip(slots, commentedLines, fileKey, num as number) : undefined}
          onClick={clickable && onLineClick ? () => onLineClick(fileKey, num as number) : undefined}
        >
          {commented ? <Icon name="comment" /> : null}
          {num ?? ""}
        </td>
        <td className={`c ${cls}`}>
          <span
            className={plainCommentClass(line.text, segs)}
            dangerouslySetInnerHTML={{ __html: codeCellHtml("", line.text, segs) }}
          />
        </td>
      </>
    );
  };
  return (
    <>
      {rows.map((row, ri) => {
        const n = row.kind === "ctx" ? row.line.newLine : row.right?.newLine;
        const hl = inHighlight(highlight, n);
        return (
          <Fragment key={row.kind === "ctx" ? `ctx-${n}-${ri}` : `pair-${row.left?.oldLine ?? ""}-${n ?? ""}-${ri}`}>
            <tr className={hl ? "hl" : undefined} id={n !== undefined ? `L-${fileKey}-${n}` : undefined}>
              {row.kind === "ctx" ? (
                <>
                  {cell(row.line, "o")}
                  {cell(row.line, "n")}
                </>
              ) : (
                <>
                  {cell(row.left, "o")}
                  {cell(row.right, "n")}
                </>
              )}
            </tr>
            {n !== undefined && slots[slotKey(fileKey, n)] != null ? (
              <SlotRow cols={4} html={slots[slotKey(fileKey, n)]} />
            ) : null}
          </Fragment>
        );
      })}
    </>
  );
}

function HunkCard({
  reviewed,
  summary,
  note,
  noteStale,
  noteDraft,
  hash,
  fileKey,
  actions,
  hunkCard,
  promotedPageId,
  reviewId,
  lookupPage,
  onOpenPage,
  onFollowUp,
}: {
  reviewed: boolean;
  summary: string | undefined;
  note: string | undefined;
  noteStale: boolean;
  noteDraft: string | undefined;
  hash: string;
  fileKey: string;
  actions: HunkActions;
  /** Activated conversation card hosted on this hunk, if any (#138). */
  hunkCard: Annotation | undefined;
  /** Page a hunk discussion moved to, if any (#138 follow-up). */
  promotedPageId: string | undefined;
  reviewId: string;
  lookupPage: (pageId: string) => Page | undefined;
  onOpenPage: (pageId: string) => void;
  onFollowUp: (cardId: string, blockId: string, index: number) => void;
}): ReactNode {
  // A promoted discussion whose page is gone reads as ordinary idle
  // (the page cannot be deleted today; defensive only).
  const promotedPage = promotedPageId ? lookupPage(promotedPageId) : undefined;
  const showPromoted = !hunkCard && promotedPage !== undefined && summary !== undefined;
  const activate = (): void => {
    // Drag-selects carry a live range and fall through to the selection
    // toolbar instead (Explain/Ask there open the page too while
    // promoted, via the toolbar's own check).
    if (!window.getSelection()?.isCollapsed) return;
    if (showPromoted && promotedPageId) {
      onOpenPage(promotedPageId);
      return;
    }
    // The explicit hunk control (issue #138): a click with no selection
    // turns the idle summary into its card (or reopens it) with no agent
    // call.
    void performAction(reviewId, { kind: "hunk_card", fileKey, contentHash: hash }, { toast: false })
      .then((res) => {
        if (!res.accepted) toast("Not available with mock data");
      })
      .catch((err: unknown) => {
        toast(`Couldn't open the summary: ${friendlyError(err)}`);
      });
  };
  return (
    <div className={`fcard${reviewed ? " rev" : ""}`}>
      {hunkCard && hunkCard.open ? (
        <ExpansionCard
          reviewId={reviewId}
          expansion={hunkCard}
          lookupPage={lookupPage}
          onOpenPage={onOpenPage}
          onFollowUp={onFollowUp}
        />
      ) : summary ? (
        <div className="fsum">
          <span className="av ai" role="img" aria-label="Agent" data-tip="Agent">
            <Icon name="spark" />
          </span>
          <p
            data-hunksum={`${fileKey}:${hash}`}
            data-tip={showPromoted ? "Open the page" : "Open as a card"}
            onClick={activate}
          >
            {summary}
          </p>
          {showPromoted && promotedPageId && promotedPage ? (
            <a
              className="cx pg"
              data-node={promotedPageId}
              title={promotedPage.title}
              aria-label={`Open page: ${promotedPage.title}`}
            >
              {promotedPage.title}
            </a>
          ) : null}
          <button
            className="ib"
            type="button"
            data-tip="Delete summary"
            aria-label="Delete summary"
            onClick={() => actions.deleteSummary(hash)}
          >
            <Icon name="trash" />
          </button>
        </div>
      ) : hunkCard && !hunkCard.open ? (
        <div className="fsum">
          <button className="tbtn xs" type="button" onClick={activate}>
            Reopen summary card
          </button>
        </div>
      ) : null}
      {note && noteDraft === undefined ? (
        <div className="fsum">
          <span className="av you" role="img" aria-label="You" data-tip="You">
            <Icon name="person" />
          </span>
          <div>
            <p style={{ margin: 0 }}>{note}</p>
            {noteStale ? <span className="hint">code changed since this note</span> : null}
          </div>
          <button
            className="ib"
            type="button"
            data-tip="Delete note"
            aria-label="Delete note"
            onClick={() => actions.deleteNote(hash)}
          >
            <Icon name="trash" />
          </button>
        </div>
      ) : null}
      {noteDraft !== undefined ? (
        <div className="composer">
          <textarea
            id={`hn-${hash}`}
            rows={2}
            placeholder="Your note on this hunk…"
            value={noteDraft}
            onChange={(e) => actions.changeNote(hash, e.target.value)}
          />
          <div className="row">
            <button className="btn ghost" type="button" onClick={() => actions.discardNote(hash)}>
              Discard
            </button>
            <button className="btn" type="button" onClick={() => actions.saveNote(hash)}>
              Save
            </button>
          </div>
        </div>
      ) : null}
    </div>
  );
}

function HiddenRow({
  file,
  indices,
  briefs,
  summaries,
  onUnhide,
}: {
  file: ReviewFile;
  indices: number[];
  briefs: Readonly<Record<string, string>> | null;
  summaries: ReadonlyMap<string, { summary?: string }>;
  onUnhide(hashes: string[]): void;
}): ReactNode {
  const reasons = [...new Set(indices.map((i) => file.hunks[i].hiddenReason).filter((r) => r !== undefined))].join(
    ", ",
  );
  const added = indices.reduce((s, i) => s + file.hunks[i].added, 0);
  const removed = indices.reduce((s, i) => s + file.hunks[i].removed, 0);
  const brief = [...new Set(
    indices.map(
      (i) =>
        briefs?.[`${file.fileKey}:${i}`] ??
        summaries.get(file.hunks[i].contentHash)?.summary ??
        hiddenDetail(file.hunks[i].hiddenReason),
    ),
  )]
    .filter(Boolean)
    .join(" ");
  return (
    // A plain block between hunk sections: never pinned, scrolls under the
    // file and hunk headers (#140).
    <div className="dhid">
      <button
        className="hid"
        type="button"
        data-tip="Show these hunks"
        aria-label={`${hiddenRunLabel(file, indices)} hidden. Show these hunks`}
        onClick={() => onUnhide(indices.map((i) => file.hunks[i].contentHash))}
      >
        <Icon name="right" />
        <span className="hidl">
          {hiddenRunLabel(file, indices)} hidden · {reasons} · +{added} −{removed}
        </span>
        <span className="hidb">{brief}</span>
      </button>
    </div>
  );
}

function HunkBlock(
  props: SectionProps & {
    index: number;
    /** Rows above the hunk's own code rows (issue #133: expand controls + revealed context). */
    beforeRows?: ReactNode;
    /** Rows below the hunk's own code rows (issue #133). */
    afterRows?: ReactNode;
    /** Unit name for the header (`· in <name>`), once a unit level expanded (issue #133). */
    unitName?: string | null;
    /** True when the shown unit came from the heuristic fallback. */
    unitApprox?: boolean;
    /** Next unit step, null when done or unavailable. */
    unitNext?: { label: string; tip: string } | null;
    unitPending?: boolean;
    onUnitExpand?: () => void;
  },
): ReactNode {
  const { file, index } = props;
  const h = file.hunks[index];
  const st = props.states.get(h.contentHash);
  const folded = st?.folded ?? false;
  const reviewed = st?.reviewed ?? false;
  const summary = st?.summary;
  const note = st?.note;
  const changedSinceReviewed = st?.stale === true;
  const noteStale = st?.noteStale === true;
  const summaryPending = st?.needsSummary === true && !summary;
  const noteDraft = props.editingNote[h.contentHash];
  const busy = !!props.busy[h.contentHash];
  const k = `${file.fileKey}:${index}`;
  const fn = h.context?.match(/(?:def|class)\s+(\w+)/)?.[1];
  const inName = props.unitName ?? fn ?? null;
  const rowProps: RowProps = {
    fileKey: file.fileKey,
    hunk: h,
    slots: props.slots,
    commentedLines: props.commentedLines,
    highlight: props.highlight,
    onLineClick: props.onLineClick,
    toks: props.tokens?.get(h.contentHash) ?? null,
  };
  return (
    // One section per hunk (#140): the header is a direct child of the file
    // flow, outside any horizontal scroller, so its vertical stick reaches
    // #right on every engine; only the code table scrolls sideways, per hunk.
    <div className="dhunk">
      <div className={`hh dhunk-h${reviewed ? " rev" : ""}`} data-hunk={k}>
        <button
          className="ib"
          type="button"
          data-tip={folded ? "Show code" : "Fold code"}
          aria-label={folded ? "Show code" : "Fold code"}
          onClick={() => props.actions.toggleFold(h.contentHash, folded)}
        >
          <Icon name={folded ? "right" : "down"} />
        </button>
        <span className="hl2" data-tip={h.header}>
          <b>
            Hunk {index + 1} of {file.hunks.length}
          </b>{" "}
          · lines {h.newStart}–{h.newEnd}
          {inName ? ` · in ${inName}` : ""}
          {props.unitApprox && props.unitName ? (
            <span className="hint" data-tip="Approximate unit: guessed without a grammar">
              {" ~"}
            </span>
          ) : null}{" "}
          ·{" "}
          <span className="st">
            <span className="a">+{h.added}</span> <span className="d">−{h.removed}</span>
          </span>
          {changedSinceReviewed ? <span className="prtag">changed since reviewed</span> : null}
        </span>
        {summaryPending && !busy ? (
          <span className="hint" data-tip="Update rewrites this summary">
            summary out of date
          </span>
        ) : null}
        {busy ? (
          <span className="hint" aria-label="Summarizing">
            <span className="dots">
              <i />
              <i />
              <i />
            </span>
          </span>
        ) : summary ? null : (
          <button
            className="ib"
            type="button"
            data-tip="Summarize with agent"
            aria-label="Summarize with agent"
            onClick={() => props.actions.summarize(h.contentHash)}
          >
            <Icon name="spark" />
          </button>
        )}
        {props.unitNext ? (
          <button
            className="ib"
            type="button"
            data-tip={props.unitNext.tip}
            aria-label={props.unitNext.tip}
            disabled={props.unitPending}
            onClick={props.onUnitExpand}
          >
            <Icon name="code" />
          </button>
        ) : null}
        <button
          className="ib"
          type="button"
          data-tip={note ? "Edit note" : "Add note"}
          aria-label={note ? "Edit note" : "Add note"}
          onClick={() => props.actions.beginNote(h.contentHash, note)}
        >
          <Icon name="note" />
        </button>
        <button
          className="ib"
          type="button"
          data-tip={reviewed ? "Mark not reviewed" : "Mark reviewed"}
          aria-label={reviewed ? "Mark not reviewed" : "Mark reviewed"}
          aria-pressed={reviewed}
          onClick={() => props.actions.toggleReviewed(h.contentHash, reviewed)}
        >
          <Icon name="check" />
        </button>
      </div>
      {summary !== undefined || note !== undefined || noteDraft !== undefined || props.hunkCards?.get(h.contentHash) !== undefined ? (
        <div className="fwrap">
          <HunkCard
            reviewed={reviewed}
            summary={summary}
            note={note}
            noteStale={noteStale}
            noteDraft={noteDraft}
            hash={h.contentHash}
            fileKey={file.fileKey}
            actions={props.actions}
            hunkCard={props.hunkCards?.get(h.contentHash)}
            promotedPageId={props.promotedHunks?.get(h.contentHash)}
            reviewId={props.reviewId}
            lookupPage={props.lookupPage ?? (() => undefined)}
            onOpenPage={props.onOpenPage ?? (() => {})}
            onFollowUp={props.onFollowUp ?? (() => {})}
          />
        </div>
      ) : null}
      {folded ? (
        <button
          className="folded"
          type="button"
          aria-label={`${h.added + h.removed} changed lines folded. Show`}
          onClick={() => props.actions.toggleFold(h.contentHash, folded)}
        >
          {h.added + h.removed} changed lines folded · show
        </button>
      ) : (
        <div className="dwrap">
          <table className={`diff ${props.view}`}>
            {props.view === "split" ? (
              <colgroup>
                <col className="cn" />
                <col />
                <col className="cn" />
                <col />
              </colgroup>
            ) : null}
            <tbody>
              {props.beforeRows}
              {props.view === "unified" ? <UnifiedRows {...rowProps} /> : <SplitRows {...rowProps} />}
              {props.afterRows}
            </tbody>
          </table>
        </div>
      )}
    </div>
  );
}

export function FileSection(props: SectionProps): ReactNode {
  const { file } = props;
  const [visible, setVisible] = useState(props.eager);
  const bodyRef = useRef<HTMLDivElement>(null);
  const stats = fileStats(file);
  const base = file.path.split("/").pop()!;
  const dir = file.path.slice(0, Math.max(0, file.path.length - base.length));
  const done = props.reviewed === file.hunks.length;
  // Expand-by-lines state (issue #133): revealed context around hunks.
  // Binary files never expand (no text to show); reviews without file
  // content hide every expansion control instead of failing per hunk.
  const canExpand = props.contentAvailable && !file.isBinary;
  const expansion = useFileExpansion(file, {
    reviewId: props.reviewId,
    headCommit: props.headCommit,
    baseCommit: props.baseCommit,
    disabled: !canExpand,
  });
  const revealedTokens = useRevealedTokens(file.path, expansion.lines, visible && !props.folded && !file.isBinary);
  // Widest line number in the file, in digits (see `--lnw` on `.dfile`).
  // Revealed lines can carry more digits than the hunks (a 4-digit file
  // with 3-digit hunks), so they widen the shared width too.
  const lineDigits = Math.max(
    1,
    ...file.hunks.flatMap((h) => h.lines.map((l) => String(l.oldLine ?? l.newLine ?? 0).length)),
    maxLineDigits(expansion.lines),
  );
  // Only rendered (unhidden) hunks tokenise; unhiding later picks up the
  // cache or tokenises on demand. Folded files skip entirely (no body).
  const renderedHunks = useMemo(
    () => (props.folded ? [] : file.hunks.filter((h) => !props.isHidden(h))),
    [props.folded, file.hunks, props.isHidden],
  );
  const fileHl = useFileHighlight(file.path, renderedHunks, visible && !props.folded && !file.isBinary);
  // Injected (test) rows win when the hook has nothing yet; otherwise the
  // hook's live rows do.
  const tokens = fileHl.byHash.size > 0 ? fileHl.byHash : (props.tokens ?? EMPTY_TOKENS);

  useEffect(() => {
    if (props.eager) {
      setVisible(true);
      return;
    }
    if (typeof IntersectionObserver === "undefined") {
      setVisible(true);
      return;
    }
    const el = bodyRef.current;
    if (!el) {
      setVisible(true);
      return;
    }
    const io = new IntersectionObserver(
      (entries) => {
        if (entries.some((e) => e.isIntersecting)) {
          setVisible(true);
          io.disconnect();
        }
      },
      { root: document.getElementById("right") ?? undefined },
    );
    io.observe(el);
    return () => io.disconnect();
  }, [props.eager]);

  // Colspan for control rows inside per-hunk tables (#140 builds one
  // table per hunk, so the parent scope owns the column count).
  const cols = props.view === "split" ? 4 : 3;

  /**
   * File body sections (issue #133 on #140's structure): hidden runs stay
   * table-free `.dhid` blocks; each shown hunk mounts edge-above /
   * revealed-above into its section's `beforeRows` and revealed-below /
   * edge-below / gap into `afterRows`. Folded hunks render no table, so
   * their expansion rows wait for unfolding.
   */
  function buildSections(): ReactNode {
    const groups = groupHunks(file.hunks, props.isHidden);
    const shown = new Set(groups.flatMap((g) => (g.type === "show" ? [g.index] : [])));
    const lastIndex = file.hunks.length - 1;
    return groups.map((g) => {
      if (g.type === "hidden") {
        return (
          <HiddenRow
            key={`hid-${g.indices.join("-")}`}
            file={file}
            indices={g.indices}
            briefs={props.briefs}
            summaries={props.states}
            onUnhide={props.onUnhide}
          />
        );
      }
      const i = g.index;
      const h = file.hunks[i];
      const u = canExpand ? expansion.unitFor(h) : null;
      const before: ReactNode[] = [];
      const after: ReactNode[] = [];
      if (canExpand) {
        const above = expansion.regionAbove(i);
        if (above) {
          before.push(
            <ExpandEdge
              key={`xa-${file.fileKey}-${i}`}
              hunk={h}
              index={i}
              side="above"
              expansion={expansion}
              file={file}
              cols={cols}
              showHide={i === 0}
            />,
          );
          // Gap lines render once, below the earlier hunk — so only the
          // top region renders lines above.
          if (i === 0) {
            const aboveLines = expansion.lines.filter((l) => l.line >= above.start && l.line <= above.end);
            if (aboveLines.length > 0) {
              before.push(
                <RevealedRows
                  key={`ra-${file.fileKey}-${i}`}
                  fileKey={file.fileKey}
                  lines={aboveLines}
                  view={props.view}
                  tokens={revealedTokens}
                  slots={props.slots}
                  highlight={props.highlight}
                />,
              );
            }
          }
        }
        const below = expansion.regionBelow(i, file.hunks);
        if (below) {
          const belowLines = expansion.lines.filter((l) => l.line >= below.start && l.line <= below.end);
          if (belowLines.length > 0) {
            after.push(
              <RevealedRows
                key={`rb-${file.fileKey}-${i}`}
                fileKey={file.fileKey}
                lines={belowLines}
                view={props.view}
                tokens={revealedTokens}
                slots={props.slots}
                highlight={props.highlight}
              />,
            );
          }
        }
        after.push(
          <ExpandEdge
            key={`xb-${file.fileKey}-${i}`}
            hunk={h}
            index={i}
            side="below"
            expansion={expansion}
            file={file}
            cols={cols}
            showHide={i === lastIndex}
          />,
        );
        // The gap row lives with the earlier hunk, and only while both
        // sides show: a fully revealed gap then reads as one run of code
        // lines, closed by the slim hide row, with the next hunk's own
        // (pinning) header below it.
        const gap = expansion.regions.find((r) => r.key === `gap-${i}`);
        if (gap && shown.has(i + 1)) {
          after.push(<ExpandGap key={`gap-${file.fileKey}-${i}`} region={gap} expansion={expansion} cols={cols} />);
        }
      }
      return (
        <HunkBlock
          key={`hunk-${file.fileKey}-${i}`}
          index={i}
          {...props}
          tokens={tokens}
          beforeRows={before}
          afterRows={after}
          unitName={u?.name ?? null}
          unitApprox={u?.approx ?? false}
          unitNext={u?.next ?? null}
          unitPending={u?.pending ?? false}
          onUnitExpand={u ? () => expansion.expandUnit(h) : undefined}
        />
      );
    });
  }

  return (
    <div
      className={`dfile${props.fileHighlighted ? " hl" : ""}`}
      id={`F-${file.fileKey}`}
      // Shared line-number width for the file's hunk tables (#140): every
      // hunk is its own table, so without this the number columns would size
      // per hunk (2-digit vs 4-digit) and code columns would start at
      // different x offsets. Digits come from the data, not the DOM.
      style={{ "--lnw": `${lineDigits}ch` } as CSSProperties}
    >
      <div className="dfile-h">
        <button
          className="ib"
          type="button"
          data-tip={props.folded ? "Expand file" : "Collapse file"}
          aria-label={props.folded ? "Expand file" : "Collapse file"}
          onClick={() => props.onToggleFileFold(file.fileKey)}
        >
          <Icon name={props.folded ? "right" : "down"} />
        </button>
        <span className="path" title={file.isRename && file.oldPath ? `${file.oldPath} → ${file.path}` : file.path}>
          <span className="dir">{dir}</span>
          <b>{base}</b>
        </span>
        {file.isRename && file.oldPath ? <span className="hint">← {file.oldPath.split("/").pop()}</span> : null}
        {file.isBinary ? <span className="gtag">binary</span> : null}
        {file.category === "generated" ? <span className="gtag">generated</span> : null}
        <span className="st">
          <span className="a">+{stats.added}</span> <span className="d">−{stats.removed}</span>
        </span>
        <span className="revc">
          {props.reviewed}/{file.hunks.length}
        </span>
        <button
          className="ib"
          type="button"
          data-tip={done ? "Mark file not reviewed" : "Mark file reviewed"}
          aria-label={done ? "Mark file not reviewed" : "Mark file reviewed"}
          aria-pressed={done}
          onClick={() => props.onMarkFileReviewed(file, done)}
        >
          <Icon name="check" />
        </button>
      </div>
      {props.folded ? null : (
        <div className="dbody" ref={bodyRef}>
          {file.isBinary ? (
            <p className="hint" style={{ padding: "6px 10px" }}>
              Binary file · changes not shown.
            </p>
          ) : visible ? (
            <>
              {buildSections()}
              {expansion.error ? (
                <div className="xerr">
                  <span>Couldn&apos;t load those lines: {expansion.error}</span>
                  <button className="tbtn xs" type="button" onClick={expansion.retry}>
                    Retry
                  </button>
                </div>
              ) : null}
            </>
          ) : (
            <div style={{ minHeight: 28 }} aria-hidden="true" />
          )}
        </div>
      )}
    </div>
  );
}
