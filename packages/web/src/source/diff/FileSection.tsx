function hasComment(
  slots: LineSlots,
  commentedLines: ReadonlySet<string>,
  fileKey: string,
  line: number,
): boolean {
  // M4: the line-number icon marks comment threads only. Expansion slots
  // render their own row without the icon; the dotted link on the quoted
  // text is their indicator (PRD §4.7).
  void slots;
  return commentedLines.has(slotKey(fileKey, line));
}

function lineTip(
  slots: LineSlots,
  commentedLines: ReadonlySet<string>,
  fileKey: string,
  line: number,
): string {
  return hasComment(slots, commentedLines, fileKey, line) ? "Show comment" : `Comment on line ${line}`;
}

